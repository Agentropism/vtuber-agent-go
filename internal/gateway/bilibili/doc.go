// Package bilibili 实现 B 站直播开放平台的接入层（执行计划 E2）。
//
// 只放连接，不放事件字段：本包负责取长连接地址、鉴权、双心跳、粘包与压缩帧拆解，
// 以及断线重连；拆出来的事件信封（{"cmd":..,"data":..}）原样交给注入的处理器，
// 由 gateway/event/bilibililive 去认字段。
//
// 与原 Rust 客户端（bilibili-live，2026-09 冻结）的差异，都属于修正原实现里
// 已经实证的缺陷：
//
//   - 压缩帧（version=2）：原实现解压后把子包放进 body_muti，却只读 body，
//     压缩帧里的所有事件被静默丢弃。这里递归摊平后逐个派发。
//   - 重连：原实现的重连循环实际不可达（内部任务永不返回），实测断连后 27 分钟
//     零次重连。这里由读超时与心跳失败驱动外层重连，并做指数退避。
//   - 帧长校验：原实现只校验上限、不校验是否超过已收字节，越界会 panic；
//     这里逐项校验并返回错误。
//   - 鉴权失败：原实现只记日志、不拆连接，客户端会以未鉴权状态永久空转；
//     这里作为错误上抛，交由重连处理。
//   - 选路：原实现用 ICMP ping，且任一条地址不通就整体启动失败；这里改成
//     逐个 TCP 拨号测速，不可达的直接跳过。
package bilibili

import "go.uber.org/zap"

// log 由 app 在启动时注入；未注入时静默。
var log = zap.NewNop()

// SetLogger 注入日志器。
func SetLogger(l *zap.Logger) {
	if l != nil {
		log = l
	}
}
