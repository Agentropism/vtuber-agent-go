// Package broadcast 提供统一播报队列(执行计划 E5)。
//
// 优先级分层:SC > 礼物 > 弹幕 > LLM 主动 > 待机。高优先级抢占低优先,
// 被打断的条目保留已合成的音频、换新序号回到同级队尾重排队;同级按入队序号 FIFO。
//
// 调度语义:
//   - 单一调度协程持有全部决策状态;合成在独立协程中并行进行(Concurrency),
//     因此下一段音频通常已经就绪。
//   - 投递遵循「不抢在更优的未落地条目前面」:只要还有优先级更高、或同优先级
//     更早入队的条目在排队或合成中,已合成好的条目就不会抢跑。这一条同时保证了
//     优先级分层与同级 FIFO——只比优先级会让同级后入队的抢跑,只统计 pending
//     则会漏掉已经提交合成的高优先级条目。
//   - MinInterval 是两次播报之间的冷却间隔。
//   - 队列满(MaxPending)时淘汰优先级最低的待合成条目;新条目本身最低则丢弃新条目。
//
// `/api/speak` 播报与会话回复都调用 Enqueue,由此消灭双播报管线。
// 合成由 Synthesizer(通常传 tts.Chain)完成,投递由 Sink 交到前端协议层。
// 条目里的 Emotion 由 Sink 带给前端做表情,队列本身不解释它。
