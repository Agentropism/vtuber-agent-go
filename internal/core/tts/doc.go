// 不随每次负载传递;需要落成文件时由调用方自行补 WAV 头。
//
// failover 链按配置顺序降级:前一个引擎失败或返回空音频时切下一个,
// 全部失败才向上返回聚合错误。引擎全部为远程 API,不做本地推理、不做音色克隆;
// 云引擎返回 mp3 时在本包内解码为 PCM。
